import argparse
import hashlib
import json
import pathlib
import re
import shutil
import subprocess

ROOT=pathlib.Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description="Prepare checksummed candidate release notes and a Linux-only Homebrew formula; never publish.")
parser.add_argument("--artifacts",type=pathlib.Path,default=ROOT/"target/dist")
parser.add_argument("--output",type=pathlib.Path,default=ROOT/"target/release-prep")
parser.add_argument("--sign-key",help="Explicit full GPG fingerprint; no default key is selected")
args=parser.parse_args()
if args.sign_key and not re.fullmatch(r"(?:[0-9A-Fa-f]{40}|[0-9A-Fa-f]{64})",args.sign_key):
    parser.error("--sign-key requires a full hexadecimal GPG fingerprint")
manifest=json.loads((args.artifacts/"manifest.json").read_text())
version=manifest["version"]
if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?",version):
    parser.error("Artifact manifest has an invalid release version")
for artifact in manifest["artifacts"]:
    name=artifact["name"]
    assert pathlib.Path(name).name==name
    assert hashlib.sha256((args.artifacts/name).read_bytes()).hexdigest()==artifact["sha256"]
args.output.mkdir(parents=True,exist_ok=True)
signature=args.output/"provenance.json.asc"
if signature.exists():
    raise SystemExit("Output contains an existing signature. Select a clean output directory to avoid stale signing evidence.")
statement=dict(schema_version="1.0",kind="traceveil.local-build-evidence",self_reported=True,version=version,platform=manifest["platform"],subjects=manifest["artifacts"],build=manifest["build"],limitations="Local command/source checks only. Not an independent builder attestation or a SLSA level claim. A signature authenticates this statement only to a separately trusted key.")
provenance=args.output/"provenance.json"
provenance.write_text(json.dumps(statement,indent=2)+"\n")
if args.sign_key:
    if not shutil.which("gpg"):
        raise SystemExit("gpg is required for explicit --sign-key")
    subprocess.run(["gpg","--batch","--armor","--local-user",args.sign_key,"--output",str(signature),"--detach-sign","--",str(provenance)],check=True)
installer=None
minimum_glibc=manifest.get("minimum_glibc")
if manifest["platform"]=="linux-x86_64":
    native=next(a for a in manifest["artifacts"] if a["kind"]=="native")
    if native["name"]!=f"traceveil-{version}-linux-x86_64.tar.gz" or not re.fullmatch(r"[a-f0-9]{64}",native["sha256"]):
        raise SystemExit("Native archive name or checksum does not match the pinned release")
    if not isinstance(minimum_glibc,str) or not re.fullmatch(r"[0-9]+(?:\.[0-9]+)+",minimum_glibc):
        raise SystemExit("Regenerate the artifact manifest with its measured glibc requirement")
    template=(ROOT/"scripts/install.sh").read_text().split("\n",1)[1]
    guard='''[ "$system-$arch" = linux-x86_64 ] || fail "This prebuilt installer supports Linux/WSL x86_64 only."
libc=$(getconf GNU_LIBC_VERSION 2>/dev/null) || fail "This prebuilt installer requires glibc. Build from source on other libc implementations."
case "$libc" in "glibc "*) libc=${libc#glibc };; *) fail "Cannot identify glibc.";; esac
printf '%s\\n' "$libc" | grep -Eq '^[0-9]+(\\.[0-9]+)+$' || fail "Cannot identify glibc."
printf '%s\\n' "$libc" | awk -v required="MINIMUM_GLIBC" '{ n=split($0,a,"."); m=split(required,b,"."); for(i=1;i<=n||i<=m;i++){if(a[i]+0>b[i]+0)exit 0;if(a[i]+0<b[i]+0)exit 1} }' || fail "Prebuilt release requires glibc MINIMUM_GLIBC or newer. Build from source on older systems."
'''.replace("MINIMUM_GLIBC",minimum_glibc)
    replacements={"version=\n":f"version='{version}'\n","sha=\n":f"sha='{native['sha256']}'\n",'if [ -z "$archive" ]; then':guard+'if [ -z "$archive" ]; then',"Install: sh install.sh --version VERSION --sha256 SHA256 [--archive FILE] [--prefix DIR] [--force]":"Install: sh install.sh [--archive FILE] [--prefix DIR] [--force]","No public download exists until a release is authorized. Prefer a locally prepared archive.":f"Pinned Traceveil {version}; archive SHA256 is embedded. No sudo or Rust required."}
    for old,new in replacements.items():
        assert template.count(old)==1,"Installer template changed; review pinned defaults before generation"
        template=template.replace(old,new,1)
    installer=args.output/"install.sh"
    installer.write_text("#!/bin/sh\n# Generated by scripts/prepare_release.py from scripts/install.sh and a verified artifact manifest.\nmain() {\n"+template+'\n}\nmain "$@"\n')
    installer.chmod(0o755)
formula=None
if manifest["platform"]=="linux-x86_64":
    native=next(a for a in manifest["artifacts"] if a["kind"]=="native")
    formula=args.output/"traceveil.rb"
    formula.write_text(f'''class Traceveil < Formula
  desc "Debug your coding agents with local evidence"
  homepage "https://github.com/zhugez/traceveil"
  url "https://github.com/zhugez/traceveil/releases/download/v{version}/{native['name']}"
  version "{version}"
  sha256 "{native['sha256']}"
  license "GPL-3.0-only"
  depends_on :linux
  depends_on arch: :x86_64

  def install
    bin.install "traceveil"
  end

  test do
    assert_match '"synthetic":true', shell_output("#{{bin}}/traceveil demo --json")
  end
end
''')
notes=f'''# Traceveil {version} candidate

Debug your coding agents.

This directory contains preparation artifacts. No release, registry package, tap or tag was published.

## Included

- Standalone production-engine synthetic demo and source-bound inspection.
- Project-scoped Pi discovery with explicit authorization and visible coverage.
- Human reports, versioned JSON, user policy, optional Pi skill installation and shell completions.
- Pinned one-line installer when available. Publish install.sh only with the exact checksummed artifact used to generate it.
- Native archive for {manifest['platform']}. Private local npm preparation is Linux x86_64/glibc only.

## Publication gates

- Obtain fresh authorization for push, tag, release and each package publication.
- Verify npm/crates ownership and Homebrew tap ownership. Name availability is not ownership.
- Run native macOS/Windows runtime, installer and PTY checks before adding support claims.
- Run brew audit/install/test on a maintained Linux tap before using the generated formula.
- Verify an actual versioned release URL and install from that URL.
- Review the self-reported provenance.json. Optional --sign-key requires an explicit maintainer fingerprint. Without it, artifacts remain unsigned. A local signature is not independent build provenance.
- Keep npm private until a separately reviewed publication design exists. The local package is not a universal multi-platform registry launcher.

## Verified artifact checksums

'''+''.join(f"- {a['name']}: {a['sha256']}\n" for a in manifest['artifacts'])
(args.output/"RELEASE_NOTES.md").write_text(notes)
print(json.dumps({"version":version,"formula":str(formula) if formula else None,"notes":str(args.output/"RELEASE_NOTES.md"),"published":False,"installer":str(installer) if installer else None,"minimum_glibc":minimum_glibc,"provenance":str(provenance),"signature":str(signature) if args.sign_key else None,"formula_validation":"Generated from verified artifact checksums; brew is not available in the local acceptance environment."}))
